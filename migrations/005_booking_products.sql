CREATE TABLE IF NOT EXISTS booking_products (
 id INTEGER PRIMARY KEY AUTOINCREMENT, slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL, price_krw INTEGER NOT NULL, extra_krw INTEGER NOT NULL, price_usd REAL NOT NULL, extra_usd REAL NOT NULL, is_visible INTEGER NOT NULL DEFAULT 1, sort_order INTEGER NOT NULL DEFAULT 10, start_date TEXT, end_date TEXT, created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
